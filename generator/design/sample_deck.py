SAMPLE_IMAGE = "sample photo"   # the key under which the sample picture is passed to the renderer


@lru_cache(maxsize=1)
def sample_photo():
    """A drawn landscape that stands in for a real photo in the examples. Returns JPEG bytes."""
    w, h = 960, 640
    image = Image.new("RGB", (w, h))
    draw = ImageDraw.Draw(image)
    top, bottom = (58, 96, 150), (236, 196, 160)             # sky: blue fading into a warm horizon
    for y in range(h):
        t = y / h
        draw.line([(0, y), (w, y)], fill=tuple(round(top[i] + (bottom[i] - top[i]) * t) for i in range(3)))
    draw.ellipse([w * 0.62, h * 0.2, w * 0.62 + 150, h * 0.2 + 150], fill=(252, 232, 190))   # sun
    for base, peak, color in [(0.62, 0.36, (96, 118, 150)), (0.72, 0.5, (66, 88, 120)), (0.84, 0.66, (38, 56, 84))]:
        points = [(0, h), (0, h * base), (w * 0.22, h * peak), (w * 0.45, h * base),
                  (w * 0.68, h * (peak + 0.06)), (w, h * (base - 0.06)), (w, h)]
        draw.polygon(points, fill=color)                     # three layers of hills, far to near
    buffer = BytesIO()
    image.save(buffer, "JPEG", quality=82)
    return buffer.getvalue()


@lru_cache(maxsize=1)
def sample_photo_url():
    """The same picture as a data: URL, for the preview in the browser."""
    return "data:image/jpeg;base64," + base64.b64encode(sample_photo()).decode()


